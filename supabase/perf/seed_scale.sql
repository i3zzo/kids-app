-- Load test data: 20,000 families (4x the 5,000 in the build plan's cost
-- estimate), 30,000 parents, 30,000 children and their real vaccination
-- schedules, 400,000 calendar events, 750,000 supply items, 300,000 sent
-- notifications. LOCAL ONLY: never run this on the real server.
--   docker exec -i supabase_db_yahal psql -U postgres < supabase/perf/seed_scale.sql
\set ON_ERROR_STOP on
\timing on
set session_replication_role = default;
select setseed(0.42);

-- Parents: 20,000 owners + 10,000 co-parents (the profile trigger runs for each)
insert into auth.users (id, phone, aud, role)
select ('00000000-0000-4000-8000-' || lpad(to_hex(n), 12, '0'))::uuid, '9656' || lpad(n::text, 7, '0'), 'authenticated', 'authenticated'
from generate_series(1, 30000) n;

insert into public.families (id, name, created_by, privacy_version)
select ('00000000-0000-4000-9000-' || lpad(to_hex(n), 12, '0'))::uuid, 'Family ' || n,
       ('00000000-0000-4000-8000-' || lpad(to_hex(n), 12, '0'))::uuid, 'privacy-2026-11-draft'
from generate_series(1, 20000) n;

insert into public.family_members (family_id, user_id, role)
select ('00000000-0000-4000-9000-' || lpad(to_hex(n), 12, '0'))::uuid, ('00000000-0000-4000-8000-' || lpad(to_hex(n), 12, '0'))::uuid, 'owner'::public.family_role
from generate_series(1, 20000) n
union all
select ('00000000-0000-4000-9000-' || lpad(to_hex(n - 20000), 12, '0'))::uuid, ('00000000-0000-4000-8000-' || lpad(to_hex(n), 12, '0'))::uuid, 'co_parent'::public.family_role
from generate_series(20001, 30000) n;

-- Children: 1 per family, plus a second in half of them (vaccination rows are generated by the trigger)
insert into public.children (family_id, first_name, birth_date, gender, nationality_group)
select ('00000000-0000-4000-9000-' || lpad(to_hex(f), 12, '0'))::uuid, 'Child ' || f || '-' || k,
       current_date - (random() * 3600)::int, case when random() < 0.5 then 'girl' else 'boy' end,
       (array['kuwaiti', 'gcc', 'other'])[1 + (random() * 2)::int]
from generate_series(1, 20000) f, generate_series(1, 2) k
where k = 1 or f % 2 = 0;

-- 20 events per family across a year; 10% repeat weekly; half have a reminder
insert into public.events (family_id, child_id, kind, title, starts_at, repeat, remind_minutes_before)
select c.family_id, c.id, 'activity', 'Event ' || e,
       now() - interval '180 days' + (random() * 360) * interval '1 day',
       case when e % 10 = 0 then 'weekly' else 'none' end,
       case when e % 2 = 0 then 60 end
from (select distinct on (family_id) family_id, id from public.children order by family_id, id) c, generate_series(1, 20) e;

-- 25 supply items per child, about 1 in 5 running low
insert into public.supply_items (family_id, child_id, category, name, quantity, low_threshold)
select c.family_id, c.id, (array['feeding','diapering','health','teething','play','clothing'])[1 + i % 6], 'Item ' || i,
       case when random() < 0.2 then 0 else 5 + (random() * 20)::int end, 1
from public.children c, generate_series(1, 25) i;

insert into public.device_tokens (token, user_id, platform)
select 'ExponentPushToken[seed' || n || ']', ('00000000-0000-4000-8000-' || lpad(to_hex(n), 12, '0'))::uuid, case when n % 2 = 0 then 'ios' else 'android' end
from generate_series(1, 30000) n;

-- History of sent reminders: 10 per parent
insert into public.notification_log (user_id, kind, ref_id, occurrence, title, body, url, sent_at)
select ('00000000-0000-4000-8000-' || lpad(to_hex(n), 12, '0'))::uuid, 'event', gen_random_uuid(), now() - k * interval '1 day', 't', 'b', '/supplies', now() - k * interval '1 day'
from generate_series(1, 30000) n, generate_series(1, 10) k;

analyze auth.users, public.profiles, public.families, public.family_members, public.children, public.child_vaccinations, public.events, public.supply_items, public.device_tokens, public.notification_log;
select (select count(*) from public.families) families, (select count(*) from public.children) children,
       (select count(*) from public.child_vaccinations) vaccinations, (select count(*) from public.events) events,
       (select count(*) from public.supply_items) supplies, (select count(*) from public.notification_log) notifications;
