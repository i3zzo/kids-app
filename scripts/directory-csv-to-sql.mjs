#!/usr/bin/env node
// Turns supabase/directory/places.csv into SQL that adds or updates directory
// listings by their `ref`. Re-running it after editing the CSV is safe: rows
// are matched on ref, and the team's own work (status, verified_on) is kept.
//   node scripts/directory-csv-to-sql.mjs > supabase/migrations/<timestamp>_directory_listings.sql
import { readFileSync } from 'node:fs';

const file = new URL('../supabase/directory/places.csv', import.meta.url);

/** RFC 4180 CSV (quoted fields, doubled quotes, newlines inside quotes). */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}

const lit = (v) => (v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => {
  if (v === '') return 'null';
  if (!/^\d+(\.\d+)?$/.test(v)) throw new Error(`not a number: ${v}`);
  return v;
};

const COLS = ['ref', 'category', 'name_ar', 'name_en', 'governorate', 'area_ar', 'area_en', 'address', 'description_ar', 'description_en',
  'min_age_months', 'max_age_months', 'phone', 'whatsapp', 'instagram', 'website', 'hours_ar', 'hours_en',
  'price_min_kwd', 'price_max_kwd', 'price_unit', 'price_note_ar', 'price_note_en', 'source_url', 'source_checked_on',
  'trending_until', 'trending_note_ar', 'trending_note_en',
  'special_needs_services', 'special_needs_note_ar', 'special_needs_note_en', 'special_needs_source_url'];
const NUMERIC = new Set(['min_age_months', 'max_age_months', 'price_min_kwd', 'price_max_kwd']);
/** "autism;speech" -> '{autism,speech}'::text[] (tags are checked by the table's constraint). */
const tags = (v) => {
  const t = v.split(';').map((x) => x.trim()).filter(Boolean);
  for (const x of t) if (!/^[a-z_]+$/.test(x)) throw new Error(`bad tag: ${x}`);
  return `'{${t.join(',')}}'::text[]`;
};
const cell = (r, c) => (NUMERIC.has(c) ? num(r[c]) : c === 'special_needs_services' ? tags(r[c]) : lit(r[c]));

const rows = parseCsv(readFileSync(file, 'utf8'));
const values = rows.map((r) => `  (${COLS.map((c) => cell(r, c)).join(', ')}, 'published')`);
const updates = COLS.filter((c) => c !== 'ref').map((c) => `  ${c} = excluded.${c}`).join(',\n');

process.stdout.write(`-- Generated by scripts/directory-csv-to-sql.mjs from supabase/directory/places.csv.
-- ${rows.length} listings from public sources. Every row records its source and
-- the date it was checked. verified_on stays null until the team confirms it.

-- The six hospitals from step 5 get a ref so the rows below update them.
update public.places p set ref = v.ref
from (values
  ('Al-Adan Hospital', 'hospital-al-adan-hospital-adan'),
  ('Al-Farwaniya Hospital', 'hospital-al-farwaniya-hospital-farwaniya'),
  ('Al-Jahra Hospital', 'hospital-al-jahra-hospital-jahra'),
  ('Mubarak Al-Kabeer Hospital', 'hospital-mubarak-al-kabeer-hospital-jabriya'),
  ('Al-Amiri Hospital', 'hospital-al-amiri-hospital-sharq'),
  ('Al-Sabah Hospital', 'hospital-al-sabah-hospital-shuwaikh')
) as v (name_en, ref)
where p.name_en = v.name_en and p.category = 'hospital' and p.ref is null;

insert into public.places (${COLS.join(', ')}, status) values
${values.join(',\n')}
on conflict (ref) do update set
${updates};
`);
